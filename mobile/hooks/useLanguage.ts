export type TranslationKey = keyof typeof TRANSLATIONS['PT'];

interface LanguageStore {
  language: Language;
  loadLanguage: () => Promise<void>;
  setLanguage: (lang: Language) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
}

export const useLanguage = create<LanguageStore>((set, get) => ({
  language: 'PT',

  async loadLanguage() {
    const saved = await authStorage.getLanguage();
    if (saved === 'PT' || saved === 'EN' || saved === 'ES') {
      set({ language: saved });
    }
  },

  setLanguage: (language: Language) => {
    set({ language });
    authStorage.saveLanguage(language).catch(() => { });
  },

  t: (key, vars) => {
    const lang = get().language || 'PT';
    let text = TRANSLATIONS[lang]?.[key] || TRANSLATIONS['PT'][key] || '';
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replace(`{${k}}`, String(v));
      }
    }
    return text;
  },
}));
